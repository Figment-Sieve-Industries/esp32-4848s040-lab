#!/usr/bin/env python3
"""Generate src/moon_photo.c (LVGL 9 RGB565 image, 180x180) from a full-moon photograph.

Usage:  python make_moon_photo.py <full-moon-image> [out.c]

Source used: NASA Scientific Visualization Studio #4768 "Moon Phase and Libration, 2020",
frame phase_full.2347.tif (3240x3240). See README.md for the URL, credit and licence.
The original is NOT kept in the repo; download it to a temp folder first.

Steps: detect the lunar disc, crop around it, resize to 180x180 with the disc centred at
(90,90) and radius 88 px, gently boost contrast, paint everything outside the disc black,
and emit a little-endian RGB565 array.
Requires Python 3 + Pillow (numpy optional, not used).
"""
import sys
from pathlib import Path
from PIL import Image, ImageEnhance, ImageFilter

SIZE = 180
CX = CY = 90
R = 88  # 2 px margin


def find_disc(img):
    """Return (cx, cy, r) of the lit disc in source pixels, from the bounding box of non-black pixels."""
    grey = img.convert("L").point(lambda v: 255 if v > 24 else 0)
    box = grey.getbbox()
    if not box:
        raise SystemExit("no disc found")
    x0, y0, x1, y1 = box
    return (x0 + x1) / 2.0, (y0 + y1) / 2.0, ((x1 - x0) + (y1 - y0)) / 4.0


def main():
    src = Path(sys.argv[1])
    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "src" / "moon_photo.c"

    img = Image.open(src).convert("RGB")
    cx, cy, r = find_disc(img)
    print(f"source disc: centre ({cx:.1f},{cy:.1f}) radius {r:.1f}")

    # crop so the disc radius maps to R px in a SIZE-px square centred on the disc
    half = r * (SIZE / 2.0) / R
    box = (cx - half, cy - half, cx + half, cy + half)
    # Pre-shrink with a box filter then Lanczos: avoids aliasing from 3240 -> 180
    crop = img.crop(tuple(int(round(v)) for v in box))
    crop = crop.resize((SIZE * 3, SIZE * 3), Image.BOX).resize((SIZE, SIZE), Image.LANCZOS)

    # gentle contrast + a touch of sharpening (the 180 px view is small)
    # The source is bright and flat: a gamma > 1 pulls the blown-out highlands down and spreads
    # the mid-tones (maria vs. highlands), then a small contrast lift.
    gamma = 1.45
    crop = crop.point([int(round(255.0 * (v / 255.0) ** gamma)) for v in range(256)] * 3)
    crop = ImageEnhance.Contrast(crop).enhance(1.12)
    crop = crop.filter(ImageFilter.UnsharpMask(radius=1.0, percent=60, threshold=2))

    px = crop.load()
    data = bytearray()
    r2 = (R + 0.5) ** 2
    for y in range(SIZE):
        for x in range(SIZE):
            dx, dy = x - CX + 0.5, y - CY + 0.5  # pixel centre relative to the disc centre
            if dx * dx + dy * dy > r2:
                rr = gg = bb = 0
            else:
                rr, gg, bb = px[x, y]
            v = ((rr & 0xF8) << 8) | ((gg & 0xFC) << 3) | (bb >> 3)
            data += bytes((v & 0xFF, v >> 8))  # little endian

    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    body = "\n".join(lines)

    text = f"""// GENERATED by tools-moon/make_moon_photo.py - do not edit by hand.
// Full moon, NASA Scientific Visualization Studio #4768 (LRO imagery), public domain.
// See tools-moon/README.md for the source and credit.
#include "moon_photo.h"

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif

static const uint8_t moon_photo_map[] LV_ATTRIBUTE_MEM_ALIGN = {{
{body}
}};

const lv_image_dsc_t moon_photo = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_RGB565,
        .flags = 0,
        .w = {SIZE},
        .h = {SIZE},
        .stride = {SIZE * 2},
        .reserved_2 = 0,
    }},
    .data_size = sizeof(moon_photo_map),
    .data = moon_photo_map,
}};
"""
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out} ({len(data)} bytes of pixel data)")

    # preview next to the script's temp dir for eyeballing
    prev = Path(sys.argv[3]) if len(sys.argv) > 3 else None
    if prev:
        pv = Image.new("RGB", (SIZE, SIZE))
        raw = bytes(data)
        pp = pv.load()
        for y in range(SIZE):
            for x in range(SIZE):
                v = raw[(y * SIZE + x) * 2] | (raw[(y * SIZE + x) * 2 + 1] << 8)
                pp[x, y] = (((v >> 11) & 31) << 3, ((v >> 5) & 63) << 2, (v & 31) << 3)
        pv.resize((540, 540), Image.NEAREST).save(prev)
        print(f"preview {prev}")


if __name__ == "__main__":
    main()
